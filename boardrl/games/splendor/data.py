@dataclass(frozen=True)
class Card:
    id: int
    tier: int
    bonus: str
    points: int
    cost: tuple[int, int, int, int, int]


@dataclass(frozen=True)
class Noble:
    id: int
    requirement: tuple[int, int, int, int, int]
    points: int = 3


